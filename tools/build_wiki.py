"""Build the GitHub Wiki from the guides in the current repository checkout.

Every guide becomes its own wiki page (in the style of feature-per-page project
wikis), each top-level folder becomes a topic hub page, and Home, _Sidebar and
_Footer are generated to tie them together. Relative links and images inside
guides are rewritten so they keep working from the wiki.
"""
import argparse
import posixpath
import re
import subprocess
from collections import defaultdict
from html import escape
from itertools import groupby
from pathlib import Path, PurePosixPath
from urllib.parse import quote

MARKER = "<!-- Generated by tools/build_wiki.py -->"
ROOT = Path(__file__).resolve().parents[1]

AREAS = {
    "📘 Foundations & Learning": ["", "CaseStudies", "Cryptography", "Homelab"],
    "🛡️ Defense & Investigations": ["IncidentResponse", "OSINT", "ReverseEngineering", "OPSEC", "Compliance"],
    "☁️ Platforms & Infrastructure": ["Cloud", "ContainerSecurity", "WebAppSecurity", "Mobile", "AI", "Data-Engineering"],
    "📡 Hardware, Wireless & Field Projects": ["Cyberdeck", "HardwareTesting", "HardwareHacking", "SDR", "Wardriving", "uConsole", "SpaceSecurity"],
    "🧰 Assessment & Field Reference": ["Tradecraft", "PlayBooks", "Checklists", "Documentation", "Scripts"],
    "📦 Downloads & Project Resources": ["PDF", "assets"],
}
EXTRA_AREA = "🗂️ Additional Topics"
TOPIC_TITLES = {
    "": "Master Guides & Repository Reference", "Documentation": "Technical Guides & Cheat Sheets",
    "AI": "Artificial Intelligence", "OSINT": "Open Source Intelligence (OSINT)",
    "OPSEC": "Operations Security (OPSEC)", "SDR": "Software-Defined Radio",
    "assets": "Illustrations & Visual Resources", "PDF": "PDF Reference Library",
    "PlayBooks": "Playbooks", "uConsole": "uConsole", "Cyberdeck": "PNWC Cyberdeck",
}
# Repository-maintenance records stay in the repo; the wiki is for readers.
MAINTENANCE = re.compile(
    r"AUDIT|REVIEW-\d|DISPOSITIONS|CLASSIFICATION|MAINTENANCE-OPERATIONS|VERIFICATION-PROTOCOL"
    r"|BRANCH-PROTECTION|REMEDIATION|^CHANGELOG$|^STYLE_GUIDE$|^DOCUMENTATION_INDEX$")
IMAGE = {".png", ".jpg", ".jpeg", ".gif", ".svg", ".webp", ".bmp", ".ico"}
SCHEME = re.compile(r"^[a-z][a-z0-9+.-]*:", re.I)
FENCE = re.compile(r"^ {0,3}(`{3,}|~{3,})")
CODE_SPAN = re.compile(r"(`+)(?:.+?)\1")
INLINE_TARGET = re.compile(r"(\]\(\s*<?)([^)\s>]+)")
HTML_TARGET = re.compile(r"""(\b(?:src|href)\s*=\s*)(["'])([^"']+)\2""", re.I)
REFERENCE = re.compile(r"^(\s{0,3}\[[^\]]+\]:\s*<?)(\S+?)(>?(?:\s|$))")


def label(text):
    return escape(text, quote=False).replace("[", "&#91;").replace("]", "&#93;").replace("|", "&#124;")


def words(text):
    return re.sub(r"(?<=[a-z])(?=[A-Z])", " ", text.replace("_", " ").replace("-", " "))


def clean_title(text):
    text = re.sub(r"<[^>]+>", "", text)
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)
    return re.sub(r"\s+", " ", text.replace("**", "").replace("`", "").strip(" #*_")).strip()


def sort_title(title):
    return re.sub(r"^[^a-z0-9]+", "", title.casefold())


def letter_band(title):
    initial = sort_title(title)[:1]
    for last, name in [("9", "0–9"), ("f", "A–F"), ("m", "G–M"), ("s", "N–S")]:
        if initial <= last:
            return name
    return "T–Z"


def slugify(text):
    slug = re.sub(r"[^A-Za-z0-9]+", "-", text.replace("&", " and ")).strip("-")
    return slug[:90].rstrip("-") or "Page"


def guide_title(root, path):
    in_code = False
    with (root / path).open(encoding="utf-8-sig", errors="replace") as source:
        for line in source:
            if FENCE.match(line):
                in_code = not in_code
            elif not in_code and line.startswith("# ") and clean_title(line[2:]):
                return clean_title(line[2:])
    return words(path.stem if path.stem.lower() != "readme" else path.parent.name)


def strip_title(text):
    """Drop a leading H1: the wiki already shows the page name as the title."""
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if line.strip() and not re.fullmatch(r"\s*(<a [^>]*></a>|<!--.*-->)\s*", line):
            if line.startswith("# "):
                del lines[i]
            break
    return "\n".join(lines).lstrip("\n")


class Linker:
    def __init__(self, repository, pages, tracked_dirs):
        self.base = f"https://github.com/{repository}"
        self.wiki = f"{self.base}/wiki/"
        self.blob = f"{self.base}/blob/main/"
        self.raw = f"https://raw.githubusercontent.com/{repository}/main/"
        self.pages = pages
        self.dirs = tracked_dirs

    def target(self, source, target):
        if not target or target.startswith("#") or SCHEME.match(target) or target.startswith("//"):
            return target
        path, hashmark, fragment = target.partition("#")
        path = path.split("?", 1)[0]
        if path.startswith("/"):
            resolved = posixpath.normpath(path.lstrip("/"))
        else:
            resolved = posixpath.normpath(posixpath.join(source.parent.as_posix(), path))
        if resolved == ".":
            resolved = ""
        if resolved.startswith(".."):
            return target
        anchor = hashmark + fragment
        readme = next((f"{resolved}/{name}".lstrip("/") for name in ("README.md", "readme.md")
                       if f"{resolved}/{name}".lstrip("/") in self.pages), None)
        if resolved in self.pages or (resolved in self.dirs and readme):
            return self.wiki + quote(self.pages[resolved if resolved in self.pages else readme]) + anchor
        if resolved in self.dirs or resolved == "":
            return f"{self.base}/tree/main/{quote(resolved)}"
        if PurePosixPath(resolved).suffix.lower() in IMAGE:
            return self.raw + quote(resolved)
        return self.blob + quote(resolved) + anchor

    def rewrite(self, source, text):
        out, fence = [], None
        for line in text.split("\n"):
            match = FENCE.match(line)
            if match and fence is None:
                fence = match.group(1)
            elif match and match.group(1)[0] == fence[0] and len(match.group(1)) >= len(fence) \
                    and not line.strip()[len(match.group(1)):].strip():
                fence = None
            elif fence is None and not line.startswith(("    ", "\t")):
                line = self._line(source, line)
            out.append(line)
        return "\n".join(out)

    def _line(self, source, line):
        # Leave inline code spans untouched; rewrite only the prose between them.
        pieces, cursor = [], 0
        for match in CODE_SPAN.finditer(line):
            pieces.append(self._prose(source, line[cursor:match.start()]))
            pieces.append(match.group(0))
            cursor = match.end()
        pieces.append(self._prose(source, line[cursor:]))
        return "".join(pieces)

    def _prose(self, source, text):
        text = INLINE_TARGET.sub(lambda m: m.group(1) + self.target(source, m.group(2)), text)
        text = HTML_TARGET.sub(lambda m: m.group(1) + m.group(2) + self.target(source, m.group(3)) + m.group(2), text)
        return REFERENCE.sub(lambda m: m.group(1) + self.target(source, m.group(2)) + m.group(3), text)


def build(output, repository, root=ROOT, tracked=None):
    root = Path(root)
    if tracked is None:
        tracked = subprocess.check_output(["git", "ls-files", "-z"], cwd=root).decode().split("\0")
    tracked = [name for name in tracked if name]
    tracked_set = set(tracked)
    tracked_dirs = {PurePosixPath(name).parent.as_posix() for name in tracked}
    tracked_dirs |= {posixpath.dirname(d) for d in list(tracked_dirs)}
    for name in tracked:
        parts = PurePosixPath(name).parts
        tracked_dirs.update("/".join(parts[:i]) for i in range(1, len(parts)))
    tracked_dirs.discard(".")

    base = f"https://github.com/{repository}"
    wiki = f"{base}/wiki/"
    blob = f"{base}/blob/main/"

    groups = defaultdict(list)
    for name in tracked:
        path = PurePosixPath(name)
        if (path.suffix.lower() != ".md" or any(p.startswith(".") for p in path.parts)
                or name == "README.md" or MAINTENANCE.search(path.stem)):
            continue
        groups[path.parts[0] if len(path.parts) > 1 else ""].append(path)

    areas = {area: [s for s in sections if s in groups] for area, sections in AREAS.items()}
    assigned = {section for sections in AREAS.values() for section in sections}
    areas[EXTRA_AREA] = sorted(groups.keys() - assigned, key=str.casefold)
    areas = {area: sections for area, sections in areas.items() if sections}

    # Name every page first so links between guides resolve to wiki pages.
    reserved = {"Home", "Browse-by-Topic", "_Sidebar", "_Footer"}
    used, page_of, hub_of, titles = set(reserved), {}, {}, {}

    def claim(*candidates):
        for candidate in candidates:
            slug = slugify(candidate)
            if slug.casefold() not in {u.casefold() for u in used}:
                used.add(slug)
                return slug
        n = 2
        while f"{slug}-{n}".casefold() in {u.casefold() for u in used}:
            n += 1
        used.add(f"{slug}-{n}")
        return f"{slug}-{n}"

    for area, sections in areas.items():
        for section in sections:
            topic = TOPIC_TITLES.get(section, words(section))
            hub_of[section] = claim(topic, topic + " Topic")
            for path in groups[section]:
                if len(path.parts) == 2 and path.stem.lower() == "readme":
                    page_of[path.as_posix()] = hub_of[section]
    for section in (s for sections in areas.values() for s in sections):
        topic = TOPIC_TITLES.get(section, words(section))
        for path in sorted(groups[section]):
            titles[path] = guide_title(root, path)
            if path.as_posix() in page_of:
                continue
            folder = words(path.parent.name) if path.parent.name else "Guide"
            # Numbered chapter titles ("01 Setup") read better with their folder name in front.
            first = f"{folder} {titles[path]}" if re.match(r"\W*\d", titles[path]) else titles[path]
            page_of[path.as_posix()] = claim(first, f"{titles[path]} {folder}",
                                             f"{titles[path]} {topic}", path.with_suffix("").as_posix())

    # The wiki's own navigation stands in for the repository's front-door indexes.
    page_of.setdefault("README.md", "Home")
    page_of.setdefault("DOCUMENTATION_INDEX.md", "Browse-by-Topic")
    linker = Linker(repository, page_of, tracked_dirs)
    pages = {}

    def link(path, title=None):
        return f"[{label(title or titles[path])}]({wiki}{quote(page_of[path.as_posix()])})"

    def source_footer(path, hub):
        return ["", "* * *", "",
                f"📄 **Source:** [`{path.as_posix()}`]({blob}{quote(path.as_posix())}) | "
                f"✏️ [Suggest an edit]({base}/edit/main/{quote(path.as_posix())}) | "
                f"⬅️ [Back to {label(hub)}]({wiki}{quote(hub_of_slug[hub])})"]

    hub_of_slug = {}
    area_rows = defaultdict(list)
    for area, sections in areas.items():
        for section in sections:
            topic = TOPIC_TITLES.get(section, words(section))
            hub_of_slug[topic] = hub_of[section]
            paths = groups[section]
            readme = next((p for p in paths if len(p.parts) == 2 and p.stem.lower() == "readme"), None)
            others = [p for p in paths if p != readme]
            area_rows[area].append((topic, hub_of[section], len(paths), readme))

            for path in others:
                body = strip_title(linker.rewrite(path, (root / path).read_text(encoding="utf-8-sig", errors="replace")))
                pages[page_of[path.as_posix()]] = [body.rstrip(), *source_footer(path, topic)]

            folders = defaultdict(list)
            for path in others:
                folders[path.parent].append(path)
            blocks = []
            for folder, documents in sorted(folders.items()):
                heading = " / ".join(words(part) for part in folder.parts[1:]) or "Guides & Reference"
                entries = sorted(documents, key=lambda p: sort_title(titles[p]))
                if len(entries) <= 20:
                    blocks.append((heading, entries))
                    continue
                for band, subset in groupby(entries, key=lambda p: letter_band(titles[p])):
                    blocks.append((f"{heading} · {band}", list(subset)))

            hub = []
            if readme:
                body = strip_title(linker.rewrite(readme, (root / readme).read_text(encoding="utf-8-sig", errors="replace")))
                hub.extend([body.rstrip(), "", "---", ""])
            else:
                hub.extend([f"Every guide in **{label(topic)}**, one page each.", "", "---", ""])
            if blocks:
                hub.extend([f"## 📑 All Pages in {label(topic)}", ""])
                for heading, entries in blocks:
                    if len(blocks) > 1:
                        hub.extend([f"### {label(heading)}", ""])
                    hub.extend(f"- {link(p)}" for p in entries)
                    hub.append("")
            hub.extend(["* * *", ""])
            tail = f"📂 **Folder:** [`{section or '/'}`]({base}/tree/main/{quote(section)})"
            if readme:
                tail += f" | ✏️ [Suggest an edit]({base}/edit/main/{quote(readme.as_posix())})"
            hub.append(tail + f" | 🗺️ [Browse by Topic]({wiki}Browse-by-Topic)")
            pages[hub_of[section]] = hub

    def wiki_or_blob(path):
        return f"{wiki}{quote(page_of[path])}" if path in page_of else f"{blob}{quote(path)}"

    document_count = sum(map(len, groups.values()))
    cover = "assets/cybersecurityguide.png"
    home = ["# 🛡️ Ultimate Cybersecurity Master Guide Wiki", ""]
    if cover in tracked_set:
        home.extend([f'<p align="center"><img src="https://raw.githubusercontent.com/{repository}/main/{cover}" '
                     'width="600" alt="Pacific Northwest Computers Ultimate Cybersecurity Master Guide"></p>', ""])
    home.extend([
        "Welcome to the official wiki of the **Ultimate Cybersecurity Master Guide** by Pacific Northwest "
        "Computers: a practitioner knowledge base for red, blue, and purple teams, students, and field technicians.",
        "", "---", "",
        f"> ***Disclaimer:*** This material is provided for authorized, ethical, and educational use only. "
        f"Only test systems you own or have written permission to assess. The maintainers are not responsible "
        f"for misuse. Read the [Legal Terms of Use & Disclaimer]({wiki_or_blob('LEGAL.md')}) before using any content.",
        "", "---", "",
        "## Introduction", "",
        f"This wiki turns the repository into a browsable reference: **{document_count} guides** across "
        f"**{sum(map(len, areas.values()))} topics**, each on its own page. Pages are rebuilt automatically "
        "from the `main` branch, so the wiki always matches the repository.",
        "", "---", "",
        "## 👉 Explore the pages in the sidebar or the topic tables below", "",
        "## 🧭 Start Here", "",
        "| Starting Point | When to Use It |", "| --- | --- |",
        f"| [Browse by Topic]({wiki}Browse-by-Topic) | See every subject area and how many pages it holds. |",
    ])
    routes = [
        ("Choose a Learning Path", "START_HERE.md", "Follow a route for your role or experience level."),
        ("Read the Master Guide", "ultimate_cybersecurity_master_guide.md", "Work through the core material in sequence."),
        ("Enhanced Master Guide", "ENHANCED_MASTER_GUIDE.md", "Go deeper once the core guide is familiar."),
        ("Specialized Topics Guide", "SPECIALIZED_TOPICS_GUIDE.md", "Niche and advanced domains."),
        ("Cybersecurity Cliff Notes", "cybersecurity_cliff_notes.md", "Quick refreshers before an engagement or exam."),
        ("Look Up a Term", "GLOSSARY.md", "Check a definition while reading a guide."),
    ]
    home.extend(f"| [{t}]({wiki_or_blob(p)}) | {d} |" for t, p, d in routes if p in tracked_set)
    for area, rows in area_rows.items():
        home.extend(["", f"## {area}", "", "| Topic | Pages |", "| --- | ---: |"])
        home.extend(f"| [{label(t)}]({wiki}{quote(s)}) | {n} |" for t, s, n, _ in rows)
    home.extend(["", "---", "", "## 🛠️ Featured Projects", ""])
    for title, path, blurb in [
        ("PNWC Cyberdeck", "Cyberdeck/README.md", "portable, authorization-first field-assessment platform"),
        ("SIEM Setup", "IncidentResponse/SIEM/README.md", "build a detection pipeline for a lab or small business"),
        ("Honeypot Lab", "IncidentResponse/HoneyPot/readme.md", "deploy and monitor deception sensors"),
        ("uConsole", "uConsole/README.md", "field-deployable hacking and SIGINT handheld"),
    ]:
        if path in tracked_set:
            home.append(f"- **[{title}]({wiki_or_blob(path)})**: {blurb}")
    home.extend([
        "", "---", "", "## 🌐 Join the Community", "",
        f"- **GitHub:** [{repository}]({base})",
        f"- **Issues:** [Report outdated content or a bug]({base}/issues)",
        f"- **Contributing:** [How to contribute]({blob}.github/CONTRIBUTING.md)",
        "- **Website:** [pnwcomputers.com](https://pnwcomputers.com)",
    ])
    pages["Home"] = home

    topics = [f"Every subject area in the guide collection. {document_count} pages in total.", ""]
    for area, rows in area_rows.items():
        topics.extend(["", f"## {area}", "", "| Topic | Pages | Section Guide |", "| --- | ---: | --- |"])
        for t, s, n, readme in rows:
            topics.append(f"| [{label(t)}]({wiki}{quote(s)}) | {n} | {'✅' if readme else '—'} |")
    pages["Browse-by-Topic"] = topics

    sidebar = [f"### [🏠 Home]({wiki}Home)", "", f"- [🗺️ Browse by Topic]({wiki}Browse-by-Topic)"]
    for title, path in [("🧭 Learning Paths", "START_HERE.md"), ("📖 Master Guide", "ultimate_cybersecurity_master_guide.md"),
                        ("🔤 Glossary", "GLOSSARY.md"), ("⚖️ Legal & Disclaimer", "LEGAL.md")]:
        if path in tracked_set:
            sidebar.append(f"- [{title}]({wiki_or_blob(path)})")
    for area, rows in area_rows.items():
        sidebar.extend(["", f"**{area}**", ""])
        sidebar.extend(f"- [{label(t)}]({wiki}{quote(s)})" for t, s, _, _ in rows)
    pages["_Sidebar"] = sidebar
    pages["_Footer"] = [f"[📂 Project Repository]({base}) | [🐞 Report an Issue]({base}/issues) | "
                        f"[🌐 PNW Computers](https://pnwcomputers.com) | [🏠 Wiki Home]({wiki}Home)"]

    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    for slug, lines in pages.items():
        (output / (slug + ".md")).write_text("\n".join([MARKER, "", *lines, ""]), encoding="utf-8")
    for old in output.glob("*.md"):
        if old.stem not in pages:
            with old.open(encoding="utf-8", errors="replace") as handle:
                if handle.readline().strip() == MARKER:
                    old.unlink()
    print(f"Built {len(pages)} wiki pages covering {document_count} guides.")
    return pages


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("output", type=Path)
    parser.add_argument("repository", help="GitHub owner/name")
    args = parser.parse_args()
    build(args.output, args.repository)
